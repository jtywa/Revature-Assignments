package challenges;

public class loops {
    public static void main(String[] args){
        // FOR LOOP

        for (int i = 1; i <= 5; i++){
            System.out.println(i);
        }

        // WHILE LOOP

        int i = 1;
        while ( i <= 5){
            System.out.println(i);
            i++;
        }

        // DO WHILE LOOP

        int j = 1;
        do {
            System.out.println(j);
            j++;
        } while (j <= 5);
    }
}
